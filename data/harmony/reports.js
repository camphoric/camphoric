import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

import { dates, earlybirdCutoff, lengthInDays } from './dates.js';

const cwd = path.dirname(fileURLToPath(import.meta.url));

// Several reports open with a Jinja preamble that hardcodes the camp dates, e.g.
//
//   {%- set dates = [ ['2025-12-30', 'Tue'], ['2025-12-31', 'Wed'], ... ] -%}
//   {%- set earlybird_cutoff = '2025-11-15T07:00:00' -%}
//
// The committed templates keep whatever year they were last exported with; the
// values are regenerated from dates.js here so every import gets the current
// camp dates. `dates` lists one [ISO date, weekday] pair per night of camp (the
// same days as camperSchema's `days`), and `earlybird_cutoff` is the cutoff in
// UTC, matching the `created_at` timestamps the reports compare it against.
const campDates = [...Array(lengthInDays).keys()]
  .map((i) => dates.start.plus({ days: i }));

const datesStatement = `{%- set dates = [${
  campDates.map((d) => `['${d.toFormat('yyyy-MM-dd')}', '${d.toFormat('EEE')}']`).join(', ')
}] -%}`;

const earlybirdStatement = `{%- set earlybird_cutoff = '${
  earlybirdCutoff.toUTC().toISO({ suppressMilliseconds: true, includeOffset: false })
}' -%}`;

const currentDates = [
  ...campDates.map((d) => d.toFormat('yyyy-MM-dd')),
  earlybirdCutoff.toUTC().toFormat('yyyy-MM-dd'),
];

function withCurrentDates(filename, template) {
  const updated = template
    .replace(/\{%-?\s*set dates\s*=\s*\[[\s\S]*?\]\s*-?%\}/, datesStatement)
    .replace(/\{%-?\s*set earlybird_cutoff\s*=\s*'[^']*'\s*-?%\}/, earlybirdStatement);

  // Any other date literal would silently go stale from one year to the next.
  const stale = (updated.match(/\d{4}-\d{2}-\d{2}/g) || [])
    .filter((d) => !currentDates.includes(d));

  if (stale.length) {
    throw new Error(
      `${filename}: hardcoded date(s) ${[...new Set(stale)].join(', ')} are not `
      + 'regenerated by reports.js; move them into a `set dates` or '
      + '`set earlybird_cutoff` preamble',
    );
  }

  return updated;
}

function readFile(filename) {
  const fullPathFilename = path.join(cwd, 'reports', filename);

  return withCurrentDates(filename, fs.readFileSync(fullPathFilename).toString());
}

